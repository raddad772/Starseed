// Builds the dune patches (src/gen/dunes.js duneField: Werner's slab model, a few seconds a patch)
// once and embeds them as base64 in src/gen/dunes.data.js, so a world's sim doesn't spend the
// time on them. The same patches dunes.js would make (it checks the parameters and makes its own
// if they differ). Run after changing DUNE or duneField:  node tools/build-dunes.mjs
import fs from 'fs';
import { duneField, DUNE } from '../src/gen/dunes.js';

const z = DUNE.supplies.map((s, k) => Buffer.from(Int16Array.from(duneField(DUNE.n, s, { iters: DUNE.iters, seed: 0xd0e5 + k })).buffer).toString('base64'));
fs.writeFileSync('src/gen/dunes.data.js', '// Generated by tools/build-dunes.mjs from src/gen/dunes.js: do not edit.\nexport const DUNE_DATA = ' + JSON.stringify({ n: DUNE.n, supplies: DUNE.supplies, iters: DUNE.iters, version: DUNE.version, z }) + ';\n');
console.log('src/gen/dunes.data.js:', z.map((x) => x.length).join(' + '), 'chars');
