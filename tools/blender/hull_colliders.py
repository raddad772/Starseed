# The carrier's hull colliders from its exterior mesh (the refit): vertical rays on a grid through the
# 'exterior' object and the refit's armour, each column's solid spans (bays come out hollow: roof and floor), merged into
# boxes, in the game's vessel frame (x starboard, y up, z aft; Blender (x, y, z) -> game (x, z, -y)).
# Writes src/sim/layouts/bastion-hull.data.js. Run in Blender (MCP):
#   exec(open('/Users/dave/dev/starseed/tools/blender/hull_colliders.py').read()); build_colliders()

import bpy, bmesh, json
from mathutils import Vector
from mathutils.bvhtree import BVHTree

OUT = '/Users/dave/dev/starseed/src/sim/layouts/bastion-hull.data.js'
STEP = 6.0      # m: the grid
QY = 2.0        # m: spans' heights rounded to this before merging
CUTS = ('room:bay-p', 'room:bay-s')
SHELL = ('exterior', 'bastion:refit_armor', 'bastion:yacht_dock_fairing')   # (the meshes the hull is)


def _tree(names):
    bm = bmesh.new()
    for n in names:
        o = bpy.data.objects.get(n)
        if o is None:
            continue
        b2 = bmesh.new(); b2.from_mesh(o.data); b2.transform(o.matrix_world)
        me = bpy.data.meshes.new('_hc'); b2.to_mesh(me); b2.free(); bm.from_mesh(me); bpy.data.meshes.remove(me)
    t = BVHTree.FromBMesh(bm); bm.free()
    return t


def _spans(t, xb, yb, cuts):
    # every surface down the line, then where it's inside: depth +1 entering (a face looking up),
    # -1 leaving; a shell left open at the bottom ends at its last hit
    hits = []
    o, d = Vector((xb, yb, 300.0)), Vector((0, 0, -1))
    for _ in range(60):
        loc, nrm, idx, dist = t.ray_cast(o, d)
        if loc is None:
            break
        hits.append((loc.z, nrm.z > 0))
        o = loc + d * 0.02
    spans, depth, top = [], 0, None
    for z, up in hits:
        if up:
            if depth == 0:
                top = z
            depth += 1
        else:
            depth = max(0, depth - 1)
            if depth == 0 and top is not None:
                spans.append((z, top)); top = None
    if top is not None and hits:
        spans.append((hits[-1][0], top))
    # the volumes open to space (the bays) cut out: plates sitting on their roofs, open underneath,
    # would otherwise leave the depth count unbalanced and fill them
    for (x0, y0, z0, x1, y1, z1) in cuts:
        if x0 <= xb <= x1 and y0 <= yb <= y1:
            out = []
            for a_, b_ in spans:
                if b_ <= z0 or a_ >= z1:
                    out.append((a_, b_)); continue
                if a_ < z0: out.append((a_, z0))
                if b_ > z1: out.append((z1, b_))
            spans = out
    q = lambda v: round(v / QY) * QY
    return tuple((q(a), q(b)) for a, b in spans if b - a > 0.3)


def build_colliders():
    t = _tree(SHELL)
    cuts = []   # (Blender frame boxes)
    for n in CUTS:
        o = bpy.data.objects.get(n)
        if o is None:
            continue
        ws = [o.matrix_world @ Vector(c) for c in o.bound_box]
        cuts.append(tuple(min(w[i] for w in ws) for i in range(3)) + tuple(max(w[i] for w in ws) for i in range(3)))
    xs = [-240 + STEP * (i + 0.5) for i in range(int(480 / STEP))]
    zs = [-700 + STEP * (k + 0.5) for k in range(int(1290 / STEP))]
    grid = {}
    for i, x in enumerate(xs):
        for k, z in enumerate(zs):
            s = _spans(t, x, -z, cuts)
            if s:
                grid[(i, k)] = s
    # each solid span on its own layer (the bays' floor is one slab however the roof above it varies):
    # greedy rectangles of cells sharing that span, along z first, then widened along x
    layers = {}
    for (i, k), s in grid.items():
        for sp in s:
            layers.setdefault(sp, set()).add((i, k))
    boxes = []
    for (y0, y1), cells in sorted(layers.items()):
        used = set()
        for (i, k) in sorted(cells):
            if (i, k) in used:
                continue
            k1 = k
            while (i, k1 + 1) in cells and (i, k1 + 1) not in used:
                k1 += 1
            i1 = i
            while all((i1 + 1, kk) in cells and (i1 + 1, kk) not in used for kk in range(k, k1 + 1)):
                i1 += 1
            for ii in range(i, i1 + 1):
                for kk in range(k, k1 + 1):
                    used.add((ii, kk))
            x0, x1 = xs[i] - STEP / 2, xs[i1] + STEP / 2
            z0, z1 = zs[k] - STEP / 2, zs[k1] + STEP / 2
            boxes.append([[round(x0, 1), y0, round(z0, 1)], [round(x1, 1), y1, round(z1, 1)]])
    with open(OUT, 'w') as f:
        f.write('// Generated by tools/blender/hull_colliders.py from the refit exterior mesh: the Bastion\'s hull\n')
        f.write('// as boxes [min, max] in its vessel frame (x starboard, y up, z aft). Do not edit by hand.\n')
        f.write('export const HULL_BOXES = ' + json.dumps(boxes, separators=(',', ':')) + ';\n')
    return len(grid), len(boxes)
