// Builds the meander trace (src/gen/meanders.js meanderTrace: Howard & Knutson's model, ~10 s)
// once and embeds it in src/gen/meanders.data.js, so no world's sampler spends the time on it.
// meanders.js makes its own if the parameters no longer match. Run after changing MEANDER or
// meanderTrace:  node tools/build-meanders.mjs
import fs from 'fs';
import { meanderTrace, MEANDER } from '../src/gen/meanders.js';

const T = meanderTrace({ P: MEANDER.P, iters: MEANDER.iters, seed: MEANDER.seed });
const r = (a) => Array.from(a, (v) => Math.round(v * 1e4) / 1e4);
const data = { ...MEANDER, x: r(T.x), y: r(T.y), oxbows: T.oxbows.map((o) => ({ x: r(o.x), y: r(o.y) })) };
fs.writeFileSync('src/gen/meanders.data.js', '// Generated by tools/build-meanders.mjs from src/gen/meanders.js: do not edit.\nexport const MEANDER_DATA = ' + JSON.stringify(data) + ';\n');
console.log('src/gen/meanders.data.js:', T.x.length, 'points,', T.oxbows.length, 'oxbows');
