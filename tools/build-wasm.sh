#!/bin/sh
# Builds native/sim.c to WebAssembly and embeds it as base64 in src/wasm/sim.wasm.js (so the
# game stays build-free and workers can compile it synchronously). Needs an LLVM clang with
# the wasm32 target and wasm-ld (Homebrew: brew install llvm lld). Run after editing sim.c.
set -e
cd "$(dirname "$0")/.."
CLANG=${CLANG:-/opt/homebrew/opt/llvm/bin/clang}
"$CLANG" --target=wasm32 -O3 -nostdlib -ffreestanding -ffp-contract=off -fno-builtin \
  -Wall -Wno-unused-function \
  -Wl,--no-entry -Wl,--export-dynamic -Wl,--strip-all -Wl,--initial-memory=1048576 \
  -o native/.sim.wasm native/sim.c
node -e "
const fs = require('fs');
const b = fs.readFileSync('native/.sim.wasm');
fs.writeFileSync('src/wasm/sim.wasm.js', '// Generated by tools/build-wasm.sh from native/sim.c: do not edit.\nexport const SIM_WASM = \'' + b.toString('base64') + '\';\n');
console.log('src/wasm/sim.wasm.js:', b.length, 'bytes of wasm');
"
rm -f native/.sim.wasm
